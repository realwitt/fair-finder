// Allowlist = booth ids with lat, minus any id that is also a ride (same cut as app.js).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const boothFile = JSON.parse(readFileSync(join(root, 'data/booths.json'), 'utf8'));
const rideFile = JSON.parse(readFileSync(join(root, 'data/rides.json'), 'utf8'));
const rideIds = new Set((rideFile.rides || []).map(r => r.id));
const ids = [];
for (const b of boothFile.booths || []) {
  if (b.lat == null || b.lon == null) continue;
  if (rideIds.has(b.id)) continue;
  ids.push(b.id);
}
ids.sort();
const CHIP_KEYS = ['hot-dog', 'corn-dog', 'turkey-leg', 'funnel-cake', 'fried-cheeseburger', 'empanada', 'lemonade', 'ice-cream', 'bbq', 'new'];
const obj = {};
for (const id of ids) obj[id] = 1;
mkdirSync(join(root, 'worker/src'), { recursive: true });
const allow = '// Generated by worker/gen-seed.mjs from data/booths.json and data/rides.json. Do not edit by hand.\n'
  + 'export const CHIP_KEYS = ' + JSON.stringify(CHIP_KEYS) + ';\n'
  + 'export const BOOTH_IDS = ' + JSON.stringify(obj) + ';\n';
writeFileSync(join(root, 'worker/src/allowlist.js'), allow);
const sql = '-- Generated by worker/gen-seed.mjs. Reference seed; the Worker validates with allowlist.js.\n'
  + ids.map(id => "INSERT INTO booths (id) VALUES ('" + id.replace(/'/g, "''") + "');").join('\n')
  + '\n';
writeFileSync(join(root, 'worker/seed-booths.sql'), sql);
process.stdout.write('allowlist ' + ids.length + ' booths\n');
